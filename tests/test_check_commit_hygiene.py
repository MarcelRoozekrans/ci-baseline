import unittest

REPO = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.normpath(os.path.join(REPO, "lib")))

import check_commit_hygiene as hygiene  # noqa: E402


class MessageTest(unittest.TestCase):
    def test_clean_message(self):
        self.assertEqual(hygiene.message_problems("a" * 40, "feat: add x\n\nPlain body (one level).\n"), [])

    def test_ai_co_author_trailer(self):
        message = "fix: y\n\nBody.\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>\n"
        problems = hygiene.message_problems("abcdef1234", message)
        self.assertEqual(len(problems), 1)
        self.assertIn("abcdef1 line 5: AI co-author trailer", problems[0])

    def test_human_co_author_is_fine(self):
        message = "fix: y\n\nCo-Authored-By: Jane Doe <jane@example.com>\n"
        self.assertEqual(hygiene.message_problems("a" * 40, message), [])

    def test_session_link_and_signature(self):
        message = (
            "docs: z\n\nGenerated with [Claude Code](https://claude.com/claude-code)\n"
            "https://claude.ai/code/session_01ABC\n"
        )
        problems = hygiene.message_problems("a" * 40, message)
        self.assertEqual(len(problems), 2)
        self.assertIn("AI signature line", problems[0])
        self.assertIn("AI session link", problems[1])

    def test_nested_parenthesis_in_body(self):
        message = "fix: x\n\nUses [Singleton(As = typeof(IDetector))] here.\n"
        problems = hygiene.message_problems("a" * 40, message)
        self.assertEqual(len(problems), 1)
        self.assertIn("line 3: nested parenthesis", problems[0])

    def test_nested_parenthesis_across_lines(self):
        message = "fix: x\n\nA note (that spans\nlines and (nests) here).\n"
        self.assertEqual(len(hygiene.message_problems("a" * 40, message)), 1)

    def test_parentheses_in_fences_and_header_are_fine(self):
        message = "fix(core): x (y)\n\n```\nfoo(bar(baz))\n```\nAfter (one level).\n"
        self.assertEqual(hygiene.message_problems("a" * 40, message), [])

    def test_body_only_flags_session_links(self):
        body = "Text.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\nhttps://claude.ai/code/session_X\n"
        self.assertEqual(hygiene.body_problems(body), ["pull request body line 5: AI session link"])


class GitTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.repo = self.tmp.name
        self.git("init", "-q")

    def tearDown(self):
        self.tmp.cleanup()

    def git(self, *args):
        return subprocess.run(
            ["git", "-C", self.repo, "-c", "user.name=t", "-c", "user.email=t@example.com", *args],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()

    def commit(self, message):
        self.git("commit", "-q", "--allow-empty", "-m", message)
        return self.git("rev-parse", "HEAD")

    def run_main(self, argv):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            code = hygiene.main(argv)
        return code, out.getvalue()

    def test_range_is_checked(self):
        base = self.commit("chore: base")
        self.commit("feat: good")
        bad = self.commit("fix: bad\n\nCo-Authored-By: Claude <noreply@anthropic.com>")
        code, out = self.run_main(["--repo", self.repo, "--from", base, "--to", bad])
        self.assertEqual(code, 1)
        self.assertIn("::error::%s line 3: AI co-author trailer" % bad[:7], out)

    def test_clean_range_and_pr_body(self):
        base = self.commit("chore: base")
        head = self.commit("feat: good\n\nBody (fine).")
        with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False) as handle:
            handle.write("A body with no session link.\n")
        try:
            code, out = self.run_main(["--repo", self.repo, "--from", base, "--to", head, "--pr-body", handle.name])
        finally:
            os.unlink(handle.name)
        self.assertEqual(code, 0)
        self.assertIn("1 commit clean", out)

    def test_unknown_range_is_an_error(self):
        code, out = self.run_main(["--repo", self.repo, "--from", "0" * 40, "--to", "HEAD"])
        self.assertEqual(code, 2)
        self.assertIn("git could not read", out)

    def test_usage(self):
        self.assertEqual(self.run_main(["--from"])[0], 2)
        self.assertEqual(self.run_main(["--to", "x"])[0], 2)


if __name__ == "__main__":
    unittest.main()
